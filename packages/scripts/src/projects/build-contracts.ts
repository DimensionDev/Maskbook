import { promises as fs } from 'node:fs'
import { join } from 'node:path'
import { task } from '../utils/task.ts'

const ABIS_PATH = join(import.meta.dirname, '../../../web3-contracts/abis/')
const GENERATED_PATH = join(import.meta.dirname, '../../../web3-contracts/types/')

export async function buildContracts() {
    await fs.rm(GENERATED_PATH, { recursive: true, force: true })
    await fs.mkdir(GENERATED_PATH, { recursive: true })

    const abis = (await fs.readdir(ABIS_PATH))
        .filter((file) => file.endsWith('.json'))
        .map((file) => file.slice(0, -'.json'.length))
        .sort((a, b) => a.localeCompare(b))

    await fs.writeFile(
        join(GENERATED_PATH, 'index.d.ts'),
        `${header()}${abis.map((abiName) => `export type { ${abiName}Abi } from './${abiName}.js'`).join('\n')}\n`,
        'utf-8',
    )

    for (const abiName of abis) {
        const abi = JSON.stringify(JSON.parse(await fs.readFile(join(ABIS_PATH, `${abiName}.json`), 'utf-8')))
        await fs.writeFile(
            join(GENERATED_PATH, `${abiName}.d.ts`),
            `${header()}// prettier-ignore\nexport type ${abiName}Abi = ${abi}\nexport const ${abiName}Abi: ${abiName}Abi\n`,
            'utf-8',
        )
        await fs.writeFile(
            join(GENERATED_PATH, `${abiName}.js`),
            `export { default as ${abiName}Abi } from '../abis/${abiName}.json' with { type: 'json' }\n`,
        )
    }
}

function header() {
    return '/* Autogenerated file. Do not edit manually. */\n/* tslint:disable */\n/* eslint-disable */\n'
}

task(buildContracts, 'build-contracts', 'Build .d.ts files from ABI files')
